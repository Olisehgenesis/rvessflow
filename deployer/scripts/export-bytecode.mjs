import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const names = [
  "TokenAllowlist",
  "ERC1967Proxy",
  "FlowConduit",
  "FlowVault",
  "VaultFactory",
  "LockVault",
  "GroupRotation",
  "ProtocolDeployer",
];

const bytecodes = {};
for (const name of names) {
  const path = resolve(root, "contracts/out", `${name}.sol`, `${name}.json`);
  const artifact = JSON.parse(readFileSync(path, "utf8"));
  const bytecode = artifact.bytecode?.object;
  if (typeof bytecode !== "string" || !bytecode.startsWith("0x") || bytecode.includes("__$")) {
    throw new Error(`${name} bytecode is missing or still has library links`);
  }
  bytecodes[name] = bytecode;
}

const out = resolve(root, "deployer/src/bytecode.ts");
writeFileSync(
  out,
  `/* Generated by scripts/export-bytecode.mjs from the Forge build. */\nexport const bytecode = ${JSON.stringify(bytecodes, null, 2)} as const;\n`,
);
console.log(`wrote ${out}`);
